import type { Endpoint } from "./config.js";

export function generateK6Script(
  endpoints: Endpoint[],
  thresholds: { p95Ms: number; failedRate: number }
): string {
  const enabled = endpoints.filter((endpoint) => endpoint.enabled);
  if (!enabled.length) throw new Error("No enabled endpoints are available to generate a script.");
  const definitions = enabled.map((endpoint) => ({
    name: endpoint.name,
    url: endpoint.url,
    method: endpoint.method,
    headers: endpoint.headers,
    body: endpoint.body ? (endpoint.bodyType === "json" ? JSON.parse(endpoint.body) : endpoint.body) : null,
    bodyType: endpoint.bodyType ?? "text"
  }));
  return `// Generated by k6boost. Review this file before running it.
 // Run independently with: k6 run <this-file>
import http from "k6/http";
import { check } from "k6";

const endpoints = ${JSON.stringify(definitions, null, 2)};

export const options = {
  thresholds: {
    http_req_duration: ["p(95)<${thresholds.p95Ms}"],
    http_req_failed: ["rate<${thresholds.failedRate}"]
  }
};

function resolveEnvironmentVariables(headers) {
  const resolved = {};
  for (const [key, value] of Object.entries(headers)) {
    const match = /^\\$\\{([A-Za-z_][A-Za-z0-9_]*)\\}$/.exec(value);
    resolved[key] = match ? (__ENV[match[1]] ?? "") : value;
  }
  return resolved;
}

export default function () {
  for (const endpoint of endpoints) {
    const headers = resolveEnvironmentVariables(endpoint.headers);
    let body = endpoint.body;
    if (endpoint.bodyType === "json" && body !== null) body = JSON.stringify(body);
    const response = http.request(endpoint.method, endpoint.url, body, {
      headers,
      tags: { endpoint: endpoint.name, method: endpoint.method },
      timeout: "30s",
      redirects: 0
    });
    check(response, {
      [endpoint.name + " responds"]: (r) => r.status >= 200 && r.status < 400
    });
  }
}
`;
}
